static mbedtls_md_type_t fg_md_type(const char *name)
{
    if (!strcmp(name, "sha256")) return MBEDTLS_MD_SHA256;
    if (!strcmp(name, "sha1")) return MBEDTLS_MD_SHA1;
    if (!strcmp(name, "sha512")) return MBEDTLS_MD_SHA512;
    if (!strcmp(name, "sha384")) return MBEDTLS_MD_SHA384;
    if (!strcmp(name, "sha224")) return MBEDTLS_MD_SHA224;
    if (!strcmp(name, "ripemd160")) return MBEDTLS_MD_RIPEMD160;
    if (!strcmp(name, "md5")) return MBEDTLS_MD_MD5;
    if (!strcmp(name, "sha3-224")) return MBEDTLS_MD_SHA3_224;
    if (!strcmp(name, "sha3-256")) return MBEDTLS_MD_SHA3_256;
    if (!strcmp(name, "sha3-384")) return MBEDTLS_MD_SHA3_384;
    if (!strcmp(name, "sha3-512")) return MBEDTLS_MD_SHA3_512;
    return MBEDTLS_MD_NONE;
}

static JSValue fg_hash(JSContext *ctx, JSValueConst this_val, int argc, JSValueConst *argv)
{
    const char *name;
    size_t len = 0;
    uint8_t *data;
    unsigned char out[64];
    const mbedtls_md_info_t *info;
    mbedtls_md_type_t type;
    int ret;

    name = JS_ToCString(ctx, argv[0]);
    if (!name) {
        return JS_EXCEPTION;
    }
    type = fg_md_type(name);
    if (type == MBEDTLS_MD_NONE) {
        JSValue err = JS_ThrowInternalError(
            ctx,
            "hash algorithm '%s' is not available in this runtime (sha1, sha256, sha512 and md5 are). "
            "Substituting a different algorithm would silently produce values that do not verify.",
            name);
        JS_FreeCString(ctx, name);
        return err;
    }
    JS_FreeCString(ctx, name);

    data = JS_GetUint8Array(ctx, &len, argv[1]);
    if (!data) {
        return JS_EXCEPTION;
    }
    info = mbedtls_md_info_from_type(type);
    ret = mbedtls_md(info, data, len, out);
    if (ret != 0) {
        return fg_throw_mbedtls(ctx, "hash", ret);
    }
    return JS_NewUint8ArrayCopy(ctx, out, mbedtls_md_get_size(info));
}

static JSValue fg_hmac(JSContext *ctx, JSValueConst this_val, int argc, JSValueConst *argv)
{
    const char *name;
    size_t key_len = 0, data_len = 0;
    uint8_t *key, *data;
    unsigned char out[64];
    const mbedtls_md_info_t *info;
    mbedtls_md_type_t type;
    int ret;

    name = JS_ToCString(ctx, argv[0]);
    if (!name) {
        return JS_EXCEPTION;
    }
    type = fg_md_type(name);
    if (type == MBEDTLS_MD_NONE || type == MBEDTLS_MD_MD5) {
        JSValue err = JS_ThrowInternalError(
            ctx, "HMAC algorithm '%s' is not available in this runtime (sha1, sha256 and sha512 are).",
            name);
        JS_FreeCString(ctx, name);
        return err;
    }
    JS_FreeCString(ctx, name);

    key = JS_GetUint8Array(ctx, &key_len, argv[1]);
    data = JS_GetUint8Array(ctx, &data_len, argv[2]);
    if (!key || !data) {
        return JS_EXCEPTION;
    }
    info = mbedtls_md_info_from_type(type);
    ret = mbedtls_md_hmac(info, key, key_len, data, data_len, out);
    if (ret != 0) {
        return fg_throw_mbedtls(ctx, "hmac", ret);
    }
    return JS_NewUint8ArrayCopy(ctx, out, mbedtls_md_get_size(info));
}

