import { parseWasmModule, type WasmExport, type WasmModuleInfo } from "./WasmModuleInfo";

/**
 * Auto-generates a plain ES module that loads a `.wasm` file and re-exports its functions as ordinary JavaScript
 * functions -- so a module written in Rust, Zig, C, Go (TinyGo) or anything else that targets `wasm32-unknown-unknown`
 * or `wasm32-wasip1` runs on Graak (wasm3 on the native host, or real `WebAssembly`/`node:wasi` on Node.js)
 * with no hand-written glue: compile to `.wasm`, ship it, `import` the generated shim next to it.
 *
 * Two shapes are recognised:
 *  - A "reactor": no imports, or only WASI imports it does not use at instantiation time. Its exports are just
 *    exposed directly; numeric ABI (i32/i64/f32/f64) needs nothing else, and a `memory` export plus common
 *    alloc/free export names get small string helpers.
 *  - A WASI "command": imports `wasi_snapshot_preview1` (or the older `wasi_unstable`) and exports `_start` or
 *    `_initialize`. The shim builds a `WASI` instance (from `node:wasi`, which Graak implements too), runs the
 *    entry point once, and exposes whatever else the module exports.
 *
 * Anything importing something else (an arbitrary `env` function) cannot be satisfied automatically -- the caller
 * would have to supply that import object itself -- so `generateShim` returns `null` for those and the packager
 * ships the `.wasm` with no generated shim, same as any other gap Graak cannot silently paper over.
 */

const STRING_ALLOC_NAMES = ["alloc", "malloc", "__wbindgen_malloc", "wasm_alloc"];
const STRING_FREE_NAMES = ["dealloc", "free", "__wbindgen_free", "wasm_free"];

/** A safe JS export binding name for a wasm export name that is not already a valid identifier. */
function jsIdentifier(name: string): string {
	return /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(name) ? name : `_${name.replace(/[^A-Za-z0-9_$]/g, "_")}`;
}

function paramList(fn: WasmExport | undefined): string {
	if (!fn?.type) return "...args";
	return fn.type.params.map((_, i) => `p${i}`).join(", ");
}

/** Whether every import the module declares is one the shim can satisfy on its own: WASI, or none at all. */
function isWasiOrReactor(info: WasmModuleInfo): { wasi: boolean; ok: boolean } {
	const nonWasi = info.imports.filter(
		(imp) => imp.module !== "wasi_snapshot_preview1" && imp.module !== "wasi_unstable"
	);
	const wasi = info.imports.some((imp) => imp.module === "wasi_snapshot_preview1" || imp.module === "wasi_unstable");
	return { wasi, ok: nonWasi.length === 0 };
}

/**
 * Builds the shim source for a parsed module, or `null` when it needs imports the shim cannot supply (the caller
 * should fall back to writing the loader by hand for those, and say so).
 */
export function generateShimSource(info: WasmModuleInfo, wasmFileName: string): string | null {
	const { wasi, ok } = isWasiOrReactor(info);
	if (!ok) return null;

	const funcExports = info.exports.filter((e) => e.kind === "func");
	const memoryExport = info.exports.find((e) => e.kind === "mem");
	const allocFn = funcExports.find((e) => STRING_ALLOC_NAMES.includes(e.name));
	const freeFn = funcExports.find((e) => STRING_FREE_NAMES.includes(e.name));
	const hasEntry = funcExports.some((e) => e.name === "_start" || e.name === "_initialize");

	const header = `// Auto-generated by Graak's WASM shim generator from ${JSON.stringify(wasmFileName)}. Do not edit by hand --
// regenerate from the .wasm instead (its own export table is the source of truth).
import { readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
${wasi ? 'import { WASI } from "node:wasi";\n' : ""}
const wasmPath = fileURLToPath(new URL(${JSON.stringify(wasmFileName)}, import.meta.url));
const wasmBytes = readFileSync(wasmPath);
// The synchronous constructors, not WebAssembly.instantiate: this file is CommonJS once packaged (the native host
// converts every ES module to it), and CommonJS require() cannot wait on top-level await.
const wasmModule = new WebAssembly.Module(wasmBytes);
`;

	const instantiate = wasi
		? `const wasi = new WASI({ version: "preview1", args: [], env: {}, returnOnExit: true });
const instance = new WebAssembly.Instance(wasmModule, wasi.getImportObject());
${hasEntry ? "wasi.start(instance);" : "wasi.initialize(instance);"}
const wasmExports = instance.exports;
`
		: `const instance = new WebAssembly.Instance(wasmModule, {});
const wasmExports = instance.exports;
`;

	const lines: string[] = [];
	for (const fn of funcExports) {
		if (fn.name === "_start" || fn.name === "_initialize") continue; // already run above for a WASI command
		const ident = jsIdentifier(fn.name);
		const params = paramList(fn);
		lines.push(`export const ${ident} = (${params}) => wasmExports[${JSON.stringify(fn.name)}](${params});`);
	}
	if (memoryExport) {
		lines.push(`export const memory = wasmExports[${JSON.stringify(memoryExport.name)}];`);
	}

	// String helpers when the module exports the common alloc/free pair alongside its memory: encode a JS string
	// into a freshly allocated buffer and call, or read a length-prefixed result back out. This is a convenience,
	// not a spec: it assumes UTF-8 bytes and a caller-owned buffer, the shape most Rust/Zig wasm32 crates use when
	// they do not bring their own string marshaling (wasm-bindgen's own glue supersedes this when present).
	let stringHelpers = "";
	if (memoryExport && allocFn && freeFn) {
		stringHelpers = `
// Convenience for the common (alloc, free, UTF-8 bytes) convention: pass a JS string, get its wasm pointer and
// byte length back; free it with wasm.freeString(ptr, len) once done, or leave it if the module frees on its own.
const textEncoder = new TextEncoder();
const textDecoder = new TextDecoder();
export function allocString(text) {
	const bytes = textEncoder.encode(text);
	const ptr = wasmExports[${JSON.stringify(allocFn.name)}](bytes.length);
	new Uint8Array(memory.buffer, ptr, bytes.length).set(bytes);
	return { ptr, len: bytes.length };
}
export function readString(ptr, len) {
	return textDecoder.decode(new Uint8Array(memory.buffer, ptr, len));
}
export function freeString(ptr, len) {
	wasmExports[${JSON.stringify(freeFn.name)}](ptr, len);
}
`;
	}

	return `${header}\n${instantiate}\n${lines.join("\n")}\n${stringHelpers}`;
}

/** Parses `wasmBytes` and returns the generated shim source, or `null` when the module needs imports the shim
 * cannot supply on its own (an arbitrary `env` import object the caller would have to provide). `wasmFileName` is
 * the relative path the shim will `import.meta.url`-resolve the `.wasm` from (normally its own file name, since the
 * shim is written next to it). */
export function generateWasmShim(wasmBytes: Uint8Array, wasmFileName: string): string | null {
	const info = parseWasmModule(wasmBytes);
	return generateShimSource(info, wasmFileName);
}
