static JSValue fg_throw_code(JSContext *ctx, const char *code, const char *fmt, const char *arg)
{
    JSValue err = JS_NewError(ctx);
    char message[256];
    snprintf(message, sizeof(message), fmt, arg);
    JS_SetPropertyStr(ctx, err, "message", JS_NewString(ctx, message));
    JS_SetPropertyStr(ctx, err, "code", JS_NewString(ctx, code));
    return JS_Throw(ctx, err);
}

/* connectStart(host, port, tls, insecure) -> id. Returns at once: the connection (and the TLS handshake) finish
   in the background and connectStatus() reports when. Blocking here would stop a program whose own server is the
   peer -- an http server and the client testing it in one process -- from ever answering. */
static JSValue fg_connect_start(JSContext *ctx, JSValueConst this_val, int argc, JSValueConst *argv)
{
    const char *host;
    char port_str[16];
    int32_t port = 0;
    int is_tls = 0, insecure = 0, id, ret;
    struct addrinfo hints, *res = NULL, *ai, *pick = NULL;
    fg_socket *sock;

    if (argc < 2 || JS_ToInt32(ctx, &port, argv[1])) {
        return JS_ThrowTypeError(ctx, "connectStart(host, port, tls, insecure, options) needs a host and a port");
    }
    host = JS_ToCString(ctx, argv[0]);
    if (!host) {
        return JS_EXCEPTION;
    }
    if (argc > 2) is_tls = JS_ToBool(ctx, argv[2]);
    if (argc > 3) insecure = JS_ToBool(ctx, argv[3]);
    id = fg_alloc_socket();
    if (id < 0) {
        JS_FreeCString(ctx, host);
        return JS_ThrowInternalError(ctx, "too many open sockets (limit is %d)", FG_MAX_SOCKETS);
    }
    if (fg_rng_init() != 0) {
        JS_FreeCString(ctx, host);
        return JS_ThrowInternalError(ctx, "could not seed the random number generator");
    }
    snprintf(port_str, sizeof(port_str), "%d", (int) port);
    memset(&hints, 0, sizeof(hints));
    hints.ai_family = AF_UNSPEC;
    hints.ai_socktype = SOCK_STREAM;
    hints.ai_protocol = IPPROTO_TCP;
    if (getaddrinfo(host, port_str, &hints, &res) != 0 || !res) {
        JSValue err = fg_throw_code(ctx, "ENOTFOUND", "getaddrinfo ENOTFOUND %s", host);
        JS_FreeCString(ctx, host);
        return err;
    }
    /* IPv4 first: an IPv4-only peer must not be missed because "localhost" listed ::1 before 127.0.0.1. */
    for (ai = res; ai; ai = ai->ai_next) {
        if (ai->ai_family == AF_INET) {
            pick = ai;
            break;
        }
    }
    if (!pick) pick = res;

    sock = &fg_sockets[id];
    memset(sock, 0, sizeof(*sock));
    mbedtls_net_init(&sock->net);
    sock->net.fd = (int) socket(pick->ai_family, pick->ai_socktype, pick->ai_protocol);
    if (sock->net.fd < 0) {
        freeaddrinfo(res);
        JS_FreeCString(ctx, host);
        return fg_throw_code(ctx, "EMFILE", "socket() failed%s", "");
    }
    mbedtls_net_set_nonblock(&sock->net);
    {
        int one = 1;
        setsockopt(sock->net.fd, IPPROTO_TCP, TCP_NODELAY, (const char *) &one, sizeof(one));
    }
    ret = connect(sock->net.fd, pick->ai_addr, (socklen_t) pick->ai_addrlen);
    freeaddrinfo(res);
    if (ret != 0) {
        int e = FG_SOCKET_ERRNO;
#ifdef _WIN32
        int pending = (e == WSAEWOULDBLOCK || e == WSAEINPROGRESS);
#else
        int pending = (e == EINPROGRESS);
#endif
        if (!pending) {
            mbedtls_net_free(&sock->net);
            memset(sock, 0, sizeof(*sock));
            JSValue err = fg_throw_code(ctx, "ECONNREFUSED", "connect ECONNREFUSED %s", host);
            JS_FreeCString(ctx, host);
            return err;
        }
        sock->connecting = 1;
    }

    if (is_tls) {
        mbedtls_ssl_init(&sock->ssl);
        mbedtls_ssl_config_init(&sock->conf);
        mbedtls_x509_crt_init(&sock->cacert);
        mbedtls_x509_crt_init(&sock->clicert);
        mbedtls_pk_init(&sock->clikey);
        if (argc > 4) {
            fg_tls_cfg_parse(ctx, argv[4], &sock->cfg);
        }
        sock->cfg.reject_unauthorized = insecure ? 0 : 1;
        ret = mbedtls_ssl_config_defaults(&sock->conf, MBEDTLS_SSL_IS_CLIENT, MBEDTLS_SSL_TRANSPORT_STREAM,
                                          MBEDTLS_SSL_PRESET_DEFAULT);
        if (ret == 0) {
            mbedtls_ssl_conf_rng(&sock->conf, mbedtls_ctr_drbg_random, &fg_drbg);
            ret = fg_tls_apply(sock, 1, insecure);
        }
        if (ret == 0) {
            ret = mbedtls_ssl_setup(&sock->ssl, &sock->conf);
        }
        if (ret == 0) {
            /* SNI, and the name the certificate is checked against. An IP literal is sent as-is. */
            ret = mbedtls_ssl_set_hostname(&sock->ssl, sock->cfg.servername ? sock->cfg.servername : host);
        }
        if (ret == 0 && argc > 5 && !JS_IsUndefined(argv[5]) && !JS_IsNull(argv[5])) {
            /* A session saved by tlsSession(): offer it so the handshake can be shortened. A stale or foreign one is ignored. */
            size_t slen = 0;
            uint8_t *sbytes = JS_GetUint8Array(ctx, &slen, argv[5]);
            if (sbytes) {
                mbedtls_ssl_session saved;
                mbedtls_ssl_session_init(&saved);
                if (mbedtls_ssl_session_load(&saved, sbytes, slen) == 0) {
                    mbedtls_ssl_set_session(&sock->ssl, &saved);
                }
                mbedtls_ssl_session_free(&saved);
            } else {
                JS_FreeValue(ctx, JS_GetException(ctx));
            }
        }
        if (ret != 0) {
            sock->in_use = 1;
            sock->is_tls = 1;
            fg_socket_release(sock);
            JSValue err = fg_throw_mbedtls(ctx, "TLS setup", ret);
            JS_FreeCString(ctx, host);
            return err;
        }
        mbedtls_ssl_set_bio(&sock->ssl, &sock->net, mbedtls_net_send, mbedtls_net_recv, NULL);
        sock->is_tls = 1;
        sock->hs_pending = 1;
    }
    sock->in_use = 1;
    JS_FreeCString(ctx, host);
    return JS_NewInt32(ctx, id);
}

/* connectStatus(id) -> true once connected (and, for TLS, handshaken), false while still working. Throws if the
   connection failed, with a Node-style `code`. */
static JSValue fg_connect_status(JSContext *ctx, JSValueConst this_val, int argc, JSValueConst *argv)
{
    int32_t id;
    fg_socket *sock;

    if (JS_ToInt32(ctx, &id, argv[0])) {
        return JS_EXCEPTION;
    }
    sock = fg_socket_get(ctx, id);
    if (!sock) {
        return JS_EXCEPTION;
    }
    if (sock->connecting) {
        int err = 0;
        socklen_t len = sizeof(err);
#ifdef _WIN32
        fd_set wset, eset;
        struct timeval tv = {0, 0};
        FD_ZERO(&wset);
        FD_ZERO(&eset);
        FD_SET((SOCKET) sock->net.fd, &wset);
        FD_SET((SOCKET) sock->net.fd, &eset);
        if (select(0, NULL, &wset, &eset, &tv) <= 0) {
            return JS_FALSE;
        }
#else
        struct pollfd pfd;
        pfd.fd = sock->net.fd;
        pfd.events = POLLOUT;
        pfd.revents = 0;
        if (poll(&pfd, 1, 0) <= 0) {
            return JS_FALSE;
        }
#endif
        getsockopt(sock->net.fd, SOL_SOCKET, SO_ERROR, (char *) &err, &len);
        if (err != 0) {
            return fg_throw_code(ctx, "ECONNREFUSED", "connect ECONNREFUSED %s", "the peer");
        }
        sock->connecting = 0;
    }
    if (sock->hs_pending) {
        int code = 0;
        int st = fg_handshake_step(sock, &code);
        if (st < 0) {
            char buf[128];
            const char *ecode = "ERR_TLS_HANDSHAKE";
            mbedtls_strerror(code, buf, sizeof(buf));
            if (code == MBEDTLS_ERR_X509_CERT_VERIFY_FAILED) {
                uint32_t flags = mbedtls_ssl_get_verify_result(&sock->ssl);
                if (flags & MBEDTLS_X509_BADCERT_EXPIRED) {
                    ecode = "CERT_HAS_EXPIRED";
                } else if (flags & MBEDTLS_X509_BADCERT_CN_MISMATCH) {
                    ecode = "ERR_TLS_CERT_ALTNAME_INVALID";
                } else if (flags & MBEDTLS_X509_BADCERT_NOT_TRUSTED) {
                    const mbedtls_x509_crt *peer = mbedtls_ssl_get_peer_cert(&sock->ssl);
                    if (!peer && sock->ssl.MBEDTLS_PRIVATE(session_negotiate)) {
                        /* A handshake that failed verification never reached the session; the negotiation still holds it. */
                        peer = sock->ssl.MBEDTLS_PRIVATE(session_negotiate)->MBEDTLS_PRIVATE(peer_cert);
                    }
                    ecode = peer && !peer->next && peer->issuer_raw.len == peer->subject_raw.len &&
                                    memcmp(peer->issuer_raw.p, peer->subject_raw.p, peer->subject_raw.len) == 0
                                ? "DEPTH_ZERO_SELF_SIGNED_CERT"
                                : "UNABLE_TO_VERIFY_LEAF_SIGNATURE";
                } else {
                    ecode = "UNABLE_TO_VERIFY_LEAF_SIGNATURE";
                }
            } else if (code == MBEDTLS_ERR_SSL_NO_APPLICATION_PROTOCOL) {
                ecode = "ERR_SSL_TLSV1_ALERT_NO_APPLICATION_PROTOCOL";
            } else if (code == MBEDTLS_ERR_SSL_FATAL_ALERT_MESSAGE) {
                /* The alert that came in is still in the record buffer: level, then description. */
                int alert = sock->ssl.MBEDTLS_PRIVATE(in_msg) ? sock->ssl.MBEDTLS_PRIVATE(in_msg)[1] : 0;
                switch (alert) {
                case 70: ecode = "ERR_SSL_TLSV1_ALERT_PROTOCOL_VERSION"; break;
                case 40: ecode = "ERR_SSL_SSL/TLS_ALERT_HANDSHAKE_FAILURE"; break;
                case 120: ecode = "ERR_SSL_TLSV1_ALERT_NO_APPLICATION_PROTOCOL"; break;
                case 116: ecode = "ERR_SSL_TLSV13_ALERT_CERTIFICATE_REQUIRED"; break;
                case 42: ecode = "ERR_SSL_SSLV3_ALERT_BAD_CERTIFICATE"; break;
                case 48: ecode = "ERR_SSL_TLSV1_ALERT_UNKNOWN_CA"; break;
                default: break;
                }
            } else if (code == MBEDTLS_ERR_SSL_BAD_PROTOCOL_VERSION) {
                ecode = "ERR_SSL_TLSV1_ALERT_PROTOCOL_VERSION";
            } else if (code == MBEDTLS_ERR_SSL_HANDSHAKE_FAILURE) {
                ecode = "ERR_SSL_SSL/TLS_ALERT_HANDSHAKE_FAILURE";
            }
            return fg_throw_code(ctx, ecode, "TLS handshake failed: %s", buf);
        }
        if (st == 0) {
            return JS_FALSE;
        }
        if (sock->cfg.deferred && sock->cfg.reject_unauthorized) {
            /* Everything but the host name is checked here; the name is the caller's to check. */
            uint32_t flags = mbedtls_ssl_get_verify_result(&sock->ssl) & ~MBEDTLS_X509_BADCERT_CN_MISMATCH;
            if (flags) {
                const char *ecode = (flags & MBEDTLS_X509_BADCERT_EXPIRED) ? "CERT_HAS_EXPIRED" : "UNABLE_TO_VERIFY_LEAF_SIGNATURE";
                return fg_throw_code(ctx, ecode, "TLS handshake failed: %s", "certificate verification failed");
            }
        }
    }
    return JS_TRUE;
}

