void graak_native_init(JSContext *ctx)
{
    JSValue global, native;

#ifdef _WIN32
    /* Winsock needs starting before any socket call, and nothing else will do it for us. */
    WSADATA wsa;
    WSAStartup(MAKEWORD(2, 2), &wsa);
#endif

    global = JS_GetGlobalObject(ctx);
    native = JS_NewObject(ctx);
    JS_SetPropertyFunctionList(ctx, native, fg_native_funcs,
                               sizeof(fg_native_funcs) / sizeof(fg_native_funcs[0]));
    /* Node-API: dlopen/LoadLibrary of `.node` addons plus the pump that delivers their async results. */
    graak_napi_init(ctx);
    JS_SetPropertyFunctionList(ctx, native, graak_napi_funcs, (int) graak_napi_funcs_count);
    /* WebAssembly (wasm3): instantiate, call exports, linear memory. node-wasm.js builds the WebAssembly API on it. */
    JS_SetPropertyFunctionList(ctx, native, graak_wasm_funcs, (int) graak_wasm_funcs_count);
    /* SQLite (amalgamation compiled in): node:sqlite and bun:sqlite are built on it. */
    JS_SetPropertyFunctionList(ctx, native, graak_sqlite_funcs, (int) graak_sqlite_funcs_count);
    JS_SetPropertyFunctionList(ctx, native, graak_crypto_funcs, (int) graak_crypto_funcs_count);
    /* ML-KEM, ML-DSA and SLH-DSA (fg_pqc.c). */
    JS_SetPropertyFunctionList(ctx, native, graak_pqc_funcs, (int) graak_pqc_funcs_count);
    /* Child processes with live pipes and the fork() IPC channel (fg_proc.c). */
    JS_SetPropertyFunctionList(ctx, native, graak_proc_funcs, (int) graak_proc_funcs_count);
    /* A single-file build's payload: the fs layer reads the program's files from it (node-sea.js). */
    fg_sea_install(ctx, native);
    JS_SetPropertyStr(ctx, native, "backend", JS_NewString(ctx, "c"));
#ifdef _WIN32
    JS_SetPropertyStr(ctx, native, "platform", JS_NewString(ctx, "win32"));
#else
    JS_SetPropertyStr(ctx, native, "platform", JS_NewString(ctx, "linux"));
#endif
    /* The architecture this binary was built for, which is what a native addon has to match. */
#if defined(__x86_64__) || defined(_M_X64)
    JS_SetPropertyStr(ctx, native, "arch", JS_NewString(ctx, "x64"));
#elif defined(__aarch64__) || defined(_M_ARM64)
    JS_SetPropertyStr(ctx, native, "arch", JS_NewString(ctx, "arm64"));
#elif defined(__arm__)
    JS_SetPropertyStr(ctx, native, "arch", JS_NewString(ctx, "arm"));
#else
    JS_SetPropertyStr(ctx, native, "arch", JS_NewString(ctx, "ia32"));
#endif
#ifdef __GLIBC__
    /* Native addons pick their glibc or musl prebuilt by asking this (Node exposes it through
       process.report), so it has to be truthful rather than guessed from the filesystem. */
    JS_SetPropertyStr(ctx, native, "glibc", JS_NewString(ctx, gnu_get_libc_version()));
#endif
    JS_SetPropertyStr(ctx, global, "__graak_native", native);
    JS_FreeValue(ctx, global);
}
