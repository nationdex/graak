typedef struct {
    char *servername;
    char *ca;         /* PEM: replaces the compiled-in bundle (client), or verifies client certificates (server) */
    char *cert;       /* PEM: a client certificate */
    char *key;
    char *passphrase;
    char *alpn;       /* protocol names joined by '\n' */
    char *ciphers;    /* mbedTLS cipher suite names joined by '\n' */
    int min_version;  /* 0 = default, 12 or 13 */
    int max_version;
    int request_cert; /* server: ask the client for a certificate */
    int reject_unauthorized; /* -1 = not given */
    int deferred;     /* client: the caller checks the host name itself (checkServerIdentity) */
} fg_tls_cfg;

static void fg_tls_cfg_free(fg_tls_cfg *c);

#define FG_MAX_SOCKETS 256

typedef struct {
    int in_use;
    int is_tls;
    int is_listener;
    int hs_pending;  /* TLS: handshake still to be stepped (server side by read/send, client side by connectStatus) */
    int connecting;  /* non-blocking connect() still in progress */
    mbedtls_net_context net;
    mbedtls_ssl_context ssl;
    mbedtls_ssl_config conf;
    mbedtls_x509_crt cacert;
    /* A TLS listener keeps its PEM so every accepted socket can build its own server context. */
    char *pem_cert;
    char *pem_key;
    mbedtls_x509_crt srvcert;
    mbedtls_pk_context srvkey;
    /* Options the caller gave (tls.connect / tls.createServer). A socket owns copies: mbedTLS keeps the ALPN list
       pointers, and a listener hands its options to every socket it accepts. */
    fg_tls_cfg cfg;
    const char *alpn_ptrs[10];
    int suites[65];    /* zero-terminated list handed to mbedTLS, which keeps the pointer */
    int reused;        /* the handshake resumed a session */
    int ticket_seen;   /* a TLS 1.3 client received a session ticket */
    mbedtls_x509_crt clicert;
    mbedtls_pk_context clikey;
} fg_socket;

/* A fixed table rather than a growing map: ids are indices, an out-of-range or unused id is
   rejected, and JavaScript therefore cannot reach memory by guessing a number. */
static fg_socket fg_sockets[FG_MAX_SOCKETS];
static mbedtls_entropy_context fg_entropy;
mbedtls_ctr_drbg_context fg_drbg;
static int fg_rng_ready = 0;

int fg_rng_init(void)
{
    static const char *pers = "graak";
    int ret;

    if (fg_rng_ready) {
        return 0;
    }
    mbedtls_entropy_init(&fg_entropy);
    mbedtls_ctr_drbg_init(&fg_drbg);
    ret = mbedtls_ctr_drbg_seed(&fg_drbg, mbedtls_entropy_func, &fg_entropy,
                                (const unsigned char *) pers, strlen(pers));
    if (ret != 0) {
        return ret;
    }
    fg_rng_ready = 1;
    return 0;
}

static JSValue fg_throw_mbedtls(JSContext *ctx, const char *what, int code)
{
    char buf[128];
    mbedtls_strerror(code, buf, sizeof(buf));
    return JS_ThrowInternalError(ctx, "%s failed: %s (-0x%04x)", what, buf, -code);
}

static fg_socket *fg_socket_get(JSContext *ctx, int32_t id)
{
    if (id < 0 || id >= FG_MAX_SOCKETS || !fg_sockets[id].in_use) {
        JS_ThrowInternalError(ctx, "socket %d does not exist (it was closed, or never opened)", id);
        return NULL;
    }
    return &fg_sockets[id];
}

static void fg_socket_release(fg_socket *sock)
{
    if (!sock->in_use) {
        return;
    }
    if (sock->is_tls) {
        if (!sock->hs_pending) {
            mbedtls_ssl_close_notify(&sock->ssl);
        }
        mbedtls_ssl_free(&sock->ssl);
        mbedtls_ssl_config_free(&sock->conf);
        mbedtls_x509_crt_free(&sock->cacert);
        mbedtls_x509_crt_free(&sock->srvcert);
        mbedtls_pk_free(&sock->srvkey);
        mbedtls_x509_crt_free(&sock->clicert);
        mbedtls_pk_free(&sock->clikey);
    }
    fg_tls_cfg_free(&sock->cfg);
    free(sock->pem_cert);
    free(sock->pem_key);
    mbedtls_net_free(&sock->net);
    memset(sock, 0, sizeof(*sock));
}

static void fg_tls_cfg_free(fg_tls_cfg *c)
{
    free(c->servername);
    free(c->ca);
    free(c->cert);
    free(c->key);
    free(c->passphrase);
    free(c->alpn);
    free(c->ciphers);
    memset(c, 0, sizeof(*c));
}

static char *fg_prop_strdup(JSContext *ctx, JSValueConst obj, const char *name)
{
    JSValue v = JS_GetPropertyStr(ctx, obj, name);
    char *out = NULL;
    if (JS_IsString(v)) {
        const char *cs = JS_ToCString(ctx, v);
        if (cs) {
            out = strdup(cs);
            JS_FreeCString(ctx, cs);
        }
    }
    JS_FreeValue(ctx, v);
    return out;
}

static int fg_prop_int(JSContext *ctx, JSValueConst obj, const char *name, int fallback)
{
    JSValue v = JS_GetPropertyStr(ctx, obj, name);
    int32_t n = fallback;
    if (JS_IsNumber(v)) {
        JS_ToInt32(ctx, &n, v);
    } else if (JS_IsBool(v)) {
        n = JS_ToBool(ctx, v);
    }
    JS_FreeValue(ctx, v);
    return n;
}

/* Reads { servername, ca, cert, key, passphrase, alpn, minVersion, maxVersion, requestCert, rejectUnauthorized }. */
static void fg_tls_cfg_parse(JSContext *ctx, JSValueConst obj, fg_tls_cfg *c)
{
    memset(c, 0, sizeof(*c));
    c->reject_unauthorized = -1;
    if (!JS_IsObject(obj)) return;
    c->servername = fg_prop_strdup(ctx, obj, "servername");
    c->ca = fg_prop_strdup(ctx, obj, "ca");
    c->cert = fg_prop_strdup(ctx, obj, "cert");
    c->key = fg_prop_strdup(ctx, obj, "key");
    c->passphrase = fg_prop_strdup(ctx, obj, "passphrase");
    c->alpn = fg_prop_strdup(ctx, obj, "alpn");
    c->ciphers = fg_prop_strdup(ctx, obj, "ciphers");
    c->min_version = fg_prop_int(ctx, obj, "minVersion", 0);
    c->max_version = fg_prop_int(ctx, obj, "maxVersion", 0);
    c->request_cert = fg_prop_int(ctx, obj, "requestCert", 0);
    c->reject_unauthorized = fg_prop_int(ctx, obj, "rejectUnauthorized", -1);
    c->deferred = fg_prop_int(ctx, obj, "deferred", 0);
}

static void fg_tls_cfg_copy(fg_tls_cfg *to, const fg_tls_cfg *from)
{
    *to = *from;
    to->servername = from->servername ? strdup(from->servername) : NULL;
    to->ca = from->ca ? strdup(from->ca) : NULL;
    to->cert = from->cert ? strdup(from->cert) : NULL;
    to->key = from->key ? strdup(from->key) : NULL;
    to->passphrase = from->passphrase ? strdup(from->passphrase) : NULL;
    to->alpn = from->alpn ? strdup(from->alpn) : NULL;
    to->ciphers = from->ciphers ? strdup(from->ciphers) : NULL;
}

/* One key for the session tickets every TLS server in the process issues: a client that comes back with one skips the
   full handshake. It is set up on first use. */
static mbedtls_ssl_ticket_context fg_ticket_ctx;
static int fg_ticket_ready = 0;

static int fg_ticket_init(void)
{
    int ret;
    if (fg_ticket_ready) {
        return 0;
    }
    mbedtls_ssl_ticket_init(&fg_ticket_ctx);
    ret = mbedtls_ssl_ticket_setup(&fg_ticket_ctx, mbedtls_ctr_drbg_random, &fg_drbg, MBEDTLS_CIPHER_AES_256_GCM, 86400);
    if (ret == 0) {
        fg_ticket_ready = 1;
    }
    return ret;
}

/* Applies the options to a socket whose ssl_config already has its defaults. `is_client` picks which side the
   certificate options mean. Returns an mbedTLS error code, or 0. */
static int fg_tls_apply(fg_socket *sock, int is_client, int insecure)
{
    fg_tls_cfg *c = &sock->cfg;
    int ret = 0;

    mbedtls_ssl_conf_renegotiation(&sock->conf, MBEDTLS_SSL_RENEGOTIATION_ENABLED);
    if (is_client) {
        mbedtls_ssl_conf_tls13_enable_signal_new_session_tickets(&sock->conf, MBEDTLS_SSL_TLS1_3_SIGNAL_NEW_SESSION_TICKETS_ENABLED);
    } else {
        ret = fg_ticket_init();
        if (ret != 0) return ret;
        mbedtls_ssl_conf_session_tickets_cb(&sock->conf, mbedtls_ssl_ticket_write, mbedtls_ssl_ticket_parse, &fg_ticket_ctx);
        mbedtls_ssl_conf_new_session_tickets(&sock->conf, 1);
    }
    if (c->ciphers && c->ciphers[0]) {
        int n = 0;
        char *copy = strdup(c->ciphers);
        char *tok = copy;
        while (copy && tok && *tok && n < 64) {
            char *nl = strchr(tok, '\n');
            int id;
            if (nl) *nl = 0;
            id = mbedtls_ssl_get_ciphersuite_id(tok);
            if (id != 0) {
                sock->suites[n++] = id;
            }
            tok = nl ? nl + 1 : NULL;
        }
        free(copy);
        sock->suites[n] = 0;
        if (n == 0) return MBEDTLS_ERR_SSL_BAD_INPUT_DATA;
        mbedtls_ssl_conf_ciphersuites(&sock->conf, sock->suites);
    }
    if (c->min_version == 13) {
        mbedtls_ssl_conf_min_tls_version(&sock->conf, MBEDTLS_SSL_VERSION_TLS1_3);
    }
    if (c->max_version == 12) {
        mbedtls_ssl_conf_max_tls_version(&sock->conf, MBEDTLS_SSL_VERSION_TLS1_2);
    }
    if (c->alpn && c->alpn[0]) {
        int n = 0;
        char *tok = c->alpn;
        char *nl;
        while (tok && *tok && n < 9) {
            sock->alpn_ptrs[n++] = tok;
            nl = strchr(tok, '\n');
            if (nl) {
                *nl = 0;
                tok = nl + 1;
            } else {
                tok = NULL;
            }
        }
        sock->alpn_ptrs[n] = NULL;
        ret = mbedtls_ssl_conf_alpn_protocols(&sock->conf, sock->alpn_ptrs);
        if (ret != 0) return ret;
    }
    if (is_client) {
        const char *pem = c->ca ? c->ca : graak_ca_bundle;
        ret = mbedtls_x509_crt_parse(&sock->cacert, (const unsigned char *) pem, strlen(pem) + 1);
        if (ret < 0) return ret;
        mbedtls_ssl_conf_authmode(&sock->conf, (insecure || c->deferred) ? MBEDTLS_SSL_VERIFY_OPTIONAL : MBEDTLS_SSL_VERIFY_REQUIRED);
        mbedtls_ssl_conf_ca_chain(&sock->conf, &sock->cacert, NULL);
        if (c->cert && c->key) {
            mbedtls_x509_crt_init(&sock->clicert);
            mbedtls_pk_init(&sock->clikey);
            ret = mbedtls_x509_crt_parse(&sock->clicert, (const unsigned char *) c->cert, strlen(c->cert) + 1);
            if (ret != 0) return ret;
            ret = mbedtls_pk_parse_key(&sock->clikey, (const unsigned char *) c->key, strlen(c->key) + 1,
                                       (const unsigned char *) c->passphrase, c->passphrase ? strlen(c->passphrase) : 0,
                                       mbedtls_ctr_drbg_random, &fg_drbg);
            if (ret != 0) return ret;
            ret = mbedtls_ssl_conf_own_cert(&sock->conf, &sock->clicert, &sock->clikey);
            if (ret != 0) return ret;
        }
    } else if (c->request_cert) {
        int reject = c->reject_unauthorized != 0;
        if (c->ca) {
            ret = mbedtls_x509_crt_parse(&sock->cacert, (const unsigned char *) c->ca, strlen(c->ca) + 1);
            if (ret < 0) return ret;
            mbedtls_ssl_conf_ca_chain(&sock->conf, &sock->cacert, NULL);
        }
        mbedtls_ssl_conf_authmode(&sock->conf, reject && c->ca ? MBEDTLS_SSL_VERIFY_REQUIRED : MBEDTLS_SSL_VERIFY_OPTIONAL);
    }
    return 0;
}

static JSValue fg_connect(JSContext *ctx, JSValueConst this_val, int argc, JSValueConst *argv)
{
    const char *host;
    char port_str[16];
    int32_t port = 0;
    int is_tls = 0;
    int insecure = 0;
    int id = -1;
    int ret;
    fg_socket *sock;

    if (argc < 2) {
        return JS_ThrowTypeError(ctx, "connect(host, port, tls, insecure) needs a host and a port");
    }
    host = JS_ToCString(ctx, argv[0]);
    if (!host) {
        return JS_EXCEPTION;
    }
    if (JS_ToInt32(ctx, &port, argv[1])) {
        JS_FreeCString(ctx, host);
        return JS_EXCEPTION;
    }
    if (argc > 2) {
        is_tls = JS_ToBool(ctx, argv[2]);
    }
    if (argc > 3) {
        insecure = JS_ToBool(ctx, argv[3]);
    }
    snprintf(port_str, sizeof(port_str), "%d", (int) port);

    for (int i = 0; i < FG_MAX_SOCKETS; i++) {
        if (!fg_sockets[i].in_use) {
            id = i;
            break;
        }
    }
    if (id < 0) {
        JS_FreeCString(ctx, host);
        return JS_ThrowInternalError(ctx, "too many open sockets (limit is %d)", FG_MAX_SOCKETS);
    }

    if (fg_rng_init() != 0) {
        JS_FreeCString(ctx, host);
        return JS_ThrowInternalError(ctx, "could not seed the random number generator");
    }

    sock = &fg_sockets[id];
    memset(sock, 0, sizeof(*sock));
    mbedtls_net_init(&sock->net);

    ret = mbedtls_net_connect(&sock->net, host, port_str, MBEDTLS_NET_PROTO_TCP);
    if (ret != 0) {
        mbedtls_net_free(&sock->net);
        JSValue err = fg_throw_mbedtls(ctx, "connect", ret);
        JS_FreeCString(ctx, host);
        return err;
    }

    if (is_tls) {
        mbedtls_ssl_init(&sock->ssl);
        mbedtls_ssl_config_init(&sock->conf);
        mbedtls_x509_crt_init(&sock->cacert);

        ret = mbedtls_x509_crt_parse(&sock->cacert, (const unsigned char *) graak_ca_bundle,
                                     strlen(graak_ca_bundle) + 1);
        if (ret < 0) {
            goto tls_failed;
        }

        ret = mbedtls_ssl_config_defaults(&sock->conf, MBEDTLS_SSL_IS_CLIENT,
                                          MBEDTLS_SSL_TRANSPORT_STREAM, MBEDTLS_SSL_PRESET_DEFAULT);
        if (ret != 0) {
            goto tls_failed;
        }
        /* Verification is required unless the caller says rejectUnauthorized: false, as Node's is: the whole
           reason for a compiled-in CA bundle is to verify properly on a machine whose own store cannot. */
        mbedtls_ssl_conf_authmode(&sock->conf, insecure ? MBEDTLS_SSL_VERIFY_NONE : MBEDTLS_SSL_VERIFY_REQUIRED);
        mbedtls_ssl_conf_ca_chain(&sock->conf, &sock->cacert, NULL);
        mbedtls_ssl_conf_rng(&sock->conf, mbedtls_ctr_drbg_random, &fg_drbg);

        ret = mbedtls_ssl_setup(&sock->ssl, &sock->conf);
        if (ret != 0) {
            goto tls_failed;
        }
        /* SNI: without it Discord's front end serves the wrong certificate. */
        ret = mbedtls_ssl_set_hostname(&sock->ssl, host);
        if (ret != 0) {
            goto tls_failed;
        }
        mbedtls_ssl_set_bio(&sock->ssl, &sock->net, mbedtls_net_send, mbedtls_net_recv, NULL);

        while ((ret = mbedtls_ssl_handshake(&sock->ssl)) != 0) {
            if (ret != MBEDTLS_ERR_SSL_WANT_READ && ret != MBEDTLS_ERR_SSL_WANT_WRITE) {
                goto tls_failed;
            }
        }
        sock->is_tls = 1;
    }

    /* Blocking while connecting and handshaking (one caller waits), non-blocking afterwards so the
       JavaScript poller can serve many sockets from one thread. */
    mbedtls_net_set_nonblock(&sock->net);
    sock->in_use = 1;
    JS_FreeCString(ctx, host);
    return JS_NewInt32(ctx, id);

tls_failed:
    mbedtls_ssl_free(&sock->ssl);
    mbedtls_ssl_config_free(&sock->conf);
    mbedtls_x509_crt_free(&sock->cacert);
    mbedtls_net_free(&sock->net);
    memset(sock, 0, sizeof(*sock));
    {
        JSValue err = fg_throw_mbedtls(ctx, "TLS handshake", ret);
        JS_FreeCString(ctx, host);
        return err;
    }
}

/* tlsInfo(id) -> { version, cipher, alpn, verify (mbedTLS flags, 0 = verified), peer: [DER, ...] } */
static JSValue fg_tls_info(JSContext *ctx, JSValueConst this_val, int argc, JSValueConst *argv)
{
    int32_t id;
    fg_socket *sock;
    JSValue o, peers;
    const mbedtls_x509_crt *crt;
    const char *alpn;
    uint32_t i = 0;

    if (JS_ToInt32(ctx, &id, argv[0])) {
        return JS_EXCEPTION;
    }
    sock = fg_socket_get(ctx, id);
    if (!sock) {
        return JS_EXCEPTION;
    }
    if (!sock->is_tls || sock->hs_pending) {
        return JS_NULL;
    }
    o = JS_NewObject(ctx);
    JS_SetPropertyStr(ctx, o, "version", JS_NewString(ctx, mbedtls_ssl_get_version(&sock->ssl)));
    JS_SetPropertyStr(ctx, o, "cipher", JS_NewString(ctx, mbedtls_ssl_get_ciphersuite(&sock->ssl)));
    alpn = mbedtls_ssl_get_alpn_protocol(&sock->ssl);
    JS_SetPropertyStr(ctx, o, "alpn", alpn ? JS_NewString(ctx, alpn) : JS_NULL);
    JS_SetPropertyStr(ctx, o, "verify", JS_NewUint32(ctx, mbedtls_ssl_get_verify_result(&sock->ssl)));
    JS_SetPropertyStr(ctx, o, "reused", JS_NewBool(ctx, sock->reused));
    JS_SetPropertyStr(ctx, o, "ticket", JS_NewBool(ctx, sock->ticket_seen));
    peers = JS_NewArray(ctx);
    for (crt = mbedtls_ssl_get_peer_cert(&sock->ssl); crt; crt = crt->next) {
        JS_SetPropertyUint32(ctx, peers, i++, JS_NewUint8ArrayCopy(ctx, crt->raw.p, crt->raw.len));
    }
    JS_SetPropertyStr(ctx, o, "peer", peers);
    return o;
}

/* tlsCiphers() -> the cipher suites this build offers, as mbedTLS names, in its own order of preference. */
static JSValue fg_tls_ciphers(JSContext *ctx, JSValueConst this_val, int argc, JSValueConst *argv)
{
    const int *list = mbedtls_ssl_list_ciphersuites();
    JSValue out = JS_NewArray(ctx);
    uint32_t n = 0;
    for (; list && *list; list++) {
        const char *name = mbedtls_ssl_get_ciphersuite_name(*list);
        if (name) {
            JS_SetPropertyUint32(ctx, out, n++, JS_NewString(ctx, name));
        }
    }
    return out;
}

/* tlsSession(id) -> the client's saved session (opaque bytes for connect's `session` option), or null. */
static JSValue fg_tls_session(JSContext *ctx, JSValueConst this_val, int argc, JSValueConst *argv)
{
    int32_t id;
    fg_socket *sock;
    mbedtls_ssl_session saved;
    size_t need = 0;
    unsigned char *bytes;
    JSValue out = JS_NULL;

    if (JS_ToInt32(ctx, &id, argv[0])) {
        return JS_EXCEPTION;
    }
    sock = fg_socket_get(ctx, id);
    if (!sock) {
        return JS_EXCEPTION;
    }
    if (!sock->is_tls || sock->hs_pending) {
        return JS_NULL;
    }
    mbedtls_ssl_session_init(&saved);
    if (mbedtls_ssl_get_session(&sock->ssl, &saved) == 0) {
        mbedtls_ssl_session_save(&saved, NULL, 0, &need);
        bytes = need ? malloc(need) : NULL;
        if (bytes && mbedtls_ssl_session_save(&saved, bytes, need, &need) == 0) {
            out = JS_NewUint8ArrayCopy(ctx, bytes, need);
        }
        free(bytes);
    }
    mbedtls_ssl_session_free(&saved);
    return out;
}

/* tlsRenegotiate(id) -> true once a renegotiation started earlier is complete. TLS 1.3 has none. */
static JSValue fg_tls_renegotiate(JSContext *ctx, JSValueConst this_val, int argc, JSValueConst *argv)
{
    int32_t id;
    fg_socket *sock;
    int ret;

    if (JS_ToInt32(ctx, &id, argv[0])) {
        return JS_EXCEPTION;
    }
    sock = fg_socket_get(ctx, id);
    if (!sock) {
        return JS_EXCEPTION;
    }
    if (!sock->is_tls || sock->hs_pending) {
        return fg_throw_code(ctx, "ERR_TLS_RENEGOTIATE", "Attempt to renegotiate TLS session failed%s", "");
    }
    if (sock->ssl.MBEDTLS_PRIVATE(tls_version) == MBEDTLS_SSL_VERSION_TLS1_3) {
        return fg_throw_code(ctx, "ERR_TLS_RENEGOTIATE", "Attempt to renegotiate TLS session failed%s", "");
    }
    ret = mbedtls_ssl_renegotiate(&sock->ssl);
    if (ret == 0) {
        return JS_TRUE;
    }
    if (ret == MBEDTLS_ERR_SSL_WANT_READ || ret == MBEDTLS_ERR_SSL_WANT_WRITE) {
        return JS_FALSE;
    }
    return fg_throw_mbedtls(ctx, "renegotiation", ret);
}

/* Waits for a descriptor, so a write that would block does not spin. */
static void fg_wait_fd(SOCKET fd, int for_write, int ms)
{
#ifdef _WIN32
    fd_set set;
    struct timeval tv;
    FD_ZERO(&set);
    FD_SET(fd, &set);
    tv.tv_sec = ms / 1000;
    tv.tv_usec = (ms % 1000) * 1000;
    select(0, for_write ? NULL : &set, for_write ? &set : NULL, NULL, &tv);
#else
    struct pollfd pfd;
    pfd.fd = fd;
    pfd.events = for_write ? POLLOUT : POLLIN;
    pfd.revents = 0;
    poll(&pfd, 1, ms);
#endif
}

/* Steps a TLS handshake. Returns 1 when done, 0 while still waiting, -1 on failure. Whether the peer resumed an
   earlier session is noted on the way, because the handshake state is gone once it finishes. */
static int fg_handshake_step(fg_socket *sock, int *code)
{
    int ret = 0;
    while (sock->ssl.MBEDTLS_PRIVATE(state) != MBEDTLS_SSL_HANDSHAKE_OVER) {
        mbedtls_ssl_handshake_params *hs = sock->ssl.MBEDTLS_PRIVATE(handshake);
        if (hs) {
            if (hs->resume) {
                sock->reused = 1;
            }
#if defined(MBEDTLS_SSL_PROTO_TLS1_3)
            if (sock->ssl.MBEDTLS_PRIVATE(tls_version) == MBEDTLS_SSL_VERSION_TLS1_3 &&
                (hs->key_exchange_mode == MBEDTLS_SSL_TLS1_3_KEY_EXCHANGE_MODE_PSK ||
                 hs->key_exchange_mode == MBEDTLS_SSL_TLS1_3_KEY_EXCHANGE_MODE_PSK_EPHEMERAL)) {
                sock->reused = 1;
            }
#endif
        }
        ret = mbedtls_ssl_handshake_step(&sock->ssl);
        if (ret != 0) {
            break;
        }
    }
    if (ret == 0) {
        sock->hs_pending = 0;
        return 1;
    }
    if (ret == MBEDTLS_ERR_SSL_WANT_READ || ret == MBEDTLS_ERR_SSL_WANT_WRITE) {
        return 0;
    }
    *code = ret;
    return -1;
}

/* read(id): a Uint8Array of what arrived, an empty one when the peer is done, or null when nothing
   has arrived yet (the socket is non-blocking; poll() says when to ask again). */
static JSValue fg_read(JSContext *ctx, JSValueConst this_val, int argc, JSValueConst *argv)
{
    int32_t id;
    fg_socket *sock;
    unsigned char buf[16384];
    int ret;

    if (JS_ToInt32(ctx, &id, argv[0])) {
        return JS_EXCEPTION;
    }
    sock = fg_socket_get(ctx, id);
    if (!sock) {
        return JS_EXCEPTION;
    }
    if (sock->is_listener) {
        return JS_ThrowTypeError(ctx, "socket %d is a listener, use accept()", id);
    }
    if (sock->hs_pending) {
        int code = 0;
        int st = fg_handshake_step(sock, &code);
        if (st < 0) {
            return fg_throw_mbedtls(ctx, "TLS handshake", code);
        }
        if (st == 0) {
            return JS_NULL;
        }
    }

    ret = sock->is_tls ? mbedtls_ssl_read(&sock->ssl, buf, sizeof(buf))
                       : mbedtls_net_recv(&sock->net, buf, sizeof(buf));
    if (ret == MBEDTLS_ERR_SSL_RECEIVED_NEW_SESSION_TICKET) {
        /* A TLS 1.3 server handed out a ticket; the session it belongs to can be read with tlsSession(). */
        sock->ticket_seen = 1;
        return JS_NULL;
    }
    if (ret == MBEDTLS_ERR_SSL_WANT_READ || ret == MBEDTLS_ERR_SSL_WANT_WRITE) {
        return JS_NULL;
    }
    /* A clean close and a zero-length read both mean "peer is done", which is what the
       JavaScript side treats as end of stream. */
    if (ret == MBEDTLS_ERR_SSL_PEER_CLOSE_NOTIFY || ret == 0) {
        return JS_NewUint8ArrayCopy(ctx, buf, 0);
    }
    if (ret < 0) {
        return fg_throw_mbedtls(ctx, "read", ret);
    }
    return JS_NewUint8ArrayCopy(ctx, buf, (size_t) ret);
}

static JSValue fg_write(JSContext *ctx, JSValueConst this_val, int argc, JSValueConst *argv)
{
    int32_t id;
    fg_socket *sock;
    size_t len = 0;
    uint8_t *data;
    size_t sent = 0;
    int waited = 0;

    if (JS_ToInt32(ctx, &id, argv[0])) {
        return JS_EXCEPTION;
    }
    sock = fg_socket_get(ctx, id);
    if (!sock) {
        return JS_EXCEPTION;
    }
    data = JS_GetUint8Array(ctx, &len, argv[1]);
    if (!data) {
        return JS_EXCEPTION;
    }

    while (sent < len) {
        int ret;
        if (sock->hs_pending) {
            int code = 0;
            int st = fg_handshake_step(sock, &code);
            if (st < 0) {
                return fg_throw_mbedtls(ctx, "TLS handshake", code);
            }
            if (st == 0) {
                fg_wait_fd(sock->net.fd, 0, 50);
                if ((waited += 50) > 30000) {
                    return JS_ThrowInternalError(ctx, "TLS handshake timed out");
                }
                continue;
            }
        }
        ret = sock->is_tls ? mbedtls_ssl_write(&sock->ssl, data + sent, len - sent)
                           : mbedtls_net_send(&sock->net, data + sent, len - sent);
        if (ret == MBEDTLS_ERR_SSL_WANT_READ || ret == MBEDTLS_ERR_SSL_WANT_WRITE) {
            fg_wait_fd(sock->net.fd, ret == MBEDTLS_ERR_SSL_WANT_WRITE, 50);
            if ((waited += 50) > 30000) {
                return JS_ThrowInternalError(ctx, "write timed out (the peer stopped reading)");
            }
            continue;
        }
        if (ret <= 0) {
            return fg_throw_mbedtls(ctx, "write", ret);
        }
        waited = 0;
        sent += (size_t) ret;
    }
    return JS_UNDEFINED;
}

/* send(id, bytes, offset) -> how many bytes were accepted (possibly 0: the socket's buffer is full or a TLS
   handshake is still going; poll() for writability and call again with the same arguments). Never blocks, so a
   program that talks to itself (a server and its client in one process) cannot deadlock on a large body. */
static JSValue fg_send(JSContext *ctx, JSValueConst this_val, int argc, JSValueConst *argv)
{
    int32_t id;
    uint32_t offset = 0;
    fg_socket *sock;
    size_t len = 0;
    uint8_t *data;
    int ret;

    if (JS_ToInt32(ctx, &id, argv[0])) {
        return JS_EXCEPTION;
    }
    sock = fg_socket_get(ctx, id);
    if (!sock) {
        return JS_EXCEPTION;
    }
    data = JS_GetUint8Array(ctx, &len, argv[1]);
    if (!data) {
        return JS_EXCEPTION;
    }
    if (argc > 2 && JS_ToUint32(ctx, &offset, argv[2])) {
        return JS_EXCEPTION;
    }
    if (offset >= len) {
        return JS_NewInt32(ctx, 0);
    }
    if (sock->hs_pending) {
        int code = 0;
        int st = fg_handshake_step(sock, &code);
        if (st < 0) {
            return fg_throw_mbedtls(ctx, "TLS handshake", code);
        }
        if (st == 0) {
            return JS_NewInt32(ctx, 0);
        }
    }
    ret = sock->is_tls ? mbedtls_ssl_write(&sock->ssl, data + offset, len - offset)
                       : mbedtls_net_send(&sock->net, data + offset, len - offset);
    if (ret == MBEDTLS_ERR_SSL_WANT_READ || ret == MBEDTLS_ERR_SSL_WANT_WRITE) {
        return JS_NewInt32(ctx, 0);
    }
    if (ret < 0) {
        return fg_throw_mbedtls(ctx, "write", ret);
    }
    return JS_NewInt32(ctx, ret);
}

/* shutdown(id): stop sending (TLS close_notify first) but keep reading until the peer is done. */
static JSValue fg_shutdown(JSContext *ctx, JSValueConst this_val, int argc, JSValueConst *argv)
{
    int32_t id;
    fg_socket *sock;

    if (JS_ToInt32(ctx, &id, argv[0])) {
        return JS_EXCEPTION;
    }
    if (id < 0 || id >= FG_MAX_SOCKETS || !fg_sockets[id].in_use || fg_sockets[id].is_listener) {
        return JS_UNDEFINED;
    }
    sock = &fg_sockets[id];
    if (sock->is_tls && !sock->hs_pending) {
        mbedtls_ssl_close_notify(&sock->ssl);
    }
#ifdef _WIN32
    shutdown(sock->net.fd, SD_SEND);
#else
    shutdown(sock->net.fd, SHUT_WR);
#endif
    return JS_UNDEFINED;
}

static JSValue fg_close(JSContext *ctx, JSValueConst this_val, int argc, JSValueConst *argv)
{
    int32_t id;

    if (JS_ToInt32(ctx, &id, argv[0])) {
        return JS_EXCEPTION;
    }
    /* Closing twice is not an error: a JavaScript stream may well destroy() after the peer
       already went away. */
    if (id >= 0 && id < FG_MAX_SOCKETS && fg_sockets[id].in_use) {
        fg_socket_release(&fg_sockets[id]);
    }
    return JS_UNDEFINED;
}

/* ----------------------------------------------------------------- servers */

static int fg_alloc_socket(void)
{
    for (int i = 0; i < FG_MAX_SOCKETS; i++) {
        if (!fg_sockets[i].in_use) {
            return i;
        }
    }
    return -1;
}

/* listen(host, port, backlog, cert?, key?) -> id. Non-blocking. With a PEM cert and key every accepted
   socket is a TLS server connection. */
static JSValue fg_listen(JSContext *ctx, JSValueConst this_val, int argc, JSValueConst *argv)
{
    const char *host = NULL;
    const char *cert = NULL, *key = NULL;
    char port_str[16];
    int32_t port = 0;
    int id, ret;
    fg_socket *sock;
    JSValue result;

    if (argc < 2 || JS_ToInt32(ctx, &port, argv[1])) {
        return JS_ThrowTypeError(ctx, "listen(host, port, backlog, cert, key, options) needs a port");
    }
    if (JS_IsString(argv[0])) {
        host = JS_ToCString(ctx, argv[0]);
        if (!host) {
            return JS_EXCEPTION;
        }
    }
    if (argc > 4 && JS_IsString(argv[3]) && JS_IsString(argv[4])) {
        cert = JS_ToCString(ctx, argv[3]);
        key = JS_ToCString(ctx, argv[4]);
    }
    id = fg_alloc_socket();
    if (id < 0) {
        result = JS_ThrowInternalError(ctx, "too many open sockets (limit is %d)", FG_MAX_SOCKETS);
        goto done;
    }
    if (fg_rng_init() != 0) {
        result = JS_ThrowInternalError(ctx, "could not seed the random number generator");
        goto done;
    }
    sock = &fg_sockets[id];
    memset(sock, 0, sizeof(*sock));
    mbedtls_net_init(&sock->net);
    snprintf(port_str, sizeof(port_str), "%d", (int) port);
    /* No host means every IPv4 interface. Windows' getaddrinfo would hand back an IPv6-only "::" first, which
       IPv4 clients cannot reach, so the wildcard is spelled out. */
    ret = mbedtls_net_bind(&sock->net, (host && host[0]) ? host : "0.0.0.0", port_str, MBEDTLS_NET_PROTO_TCP);
    if (ret != 0) {
        mbedtls_net_free(&sock->net);
        result = fg_throw_mbedtls(ctx, "listen", ret);
        goto done;
    }
    sock->in_use = 1;
    if (argc > 5) {
        fg_tls_cfg_parse(ctx, argv[5], &sock->cfg);
    }
    if (cert && key) {
        sock->pem_cert = strdup(cert);
        sock->pem_key = strdup(key);
        if (!sock->pem_cert || !sock->pem_key) {
            fg_socket_release(sock);
            result = JS_ThrowOutOfMemory(ctx);
            goto done;
        }
        /* Fail now, not on the first request, if the certificate or key cannot be read. */
        mbedtls_x509_crt probe_crt;
        mbedtls_pk_context probe_key;
        mbedtls_x509_crt_init(&probe_crt);
        mbedtls_pk_init(&probe_key);
        ret = mbedtls_x509_crt_parse(&probe_crt, (const unsigned char *) cert, strlen(cert) + 1);
        if (ret == 0) {
            ret = mbedtls_pk_parse_key(&probe_key, (const unsigned char *) key, strlen(key) + 1,
                                       (const unsigned char *) sock->cfg.passphrase,
                                       sock->cfg.passphrase ? strlen(sock->cfg.passphrase) : 0, mbedtls_ctr_drbg_random,
                                       &fg_drbg);
        }
        mbedtls_x509_crt_free(&probe_crt);
        mbedtls_pk_free(&probe_key);
        if (ret != 0) {
            fg_socket_release(sock);
            result = fg_throw_mbedtls(ctx, "certificate or key", ret);
            goto done;
        }
    }
    mbedtls_net_set_nonblock(&sock->net);
    sock->is_listener = 1;
    sock->in_use = 1;
    result = JS_NewInt32(ctx, id);
done:
    if (host) JS_FreeCString(ctx, host);
    if (cert) JS_FreeCString(ctx, cert);
    if (key) JS_FreeCString(ctx, key);
    return result;
}

/* accept(listenerId) -> socket id, or null when nobody is waiting. */
static JSValue fg_accept(JSContext *ctx, JSValueConst this_val, int argc, JSValueConst *argv)
{
    int32_t lid;
    fg_socket *lis, *sock;
    int id, ret;

    if (JS_ToInt32(ctx, &lid, argv[0])) {
        return JS_EXCEPTION;
    }
    lis = fg_socket_get(ctx, lid);
    if (!lis) {
        return JS_EXCEPTION;
    }
    if (!lis->is_listener) {
        return JS_ThrowTypeError(ctx, "socket %d is not a listener", lid);
    }
    id = fg_alloc_socket();
    if (id < 0) {
        return JS_ThrowInternalError(ctx, "too many open sockets (limit is %d)", FG_MAX_SOCKETS);
    }
    sock = &fg_sockets[id];
    memset(sock, 0, sizeof(*sock));
    mbedtls_net_init(&sock->net);
    ret = mbedtls_net_accept(&lis->net, &sock->net, NULL, 0, NULL);
    if (ret == MBEDTLS_ERR_SSL_WANT_READ) {
        mbedtls_net_free(&sock->net);
        return JS_NULL;
    }
    if (ret != 0) {
        mbedtls_net_free(&sock->net);
        return fg_throw_mbedtls(ctx, "accept", ret);
    }
    mbedtls_net_set_nonblock(&sock->net);
    {
        int one = 1;
        setsockopt(sock->net.fd, IPPROTO_TCP, TCP_NODELAY, (const char *) &one, sizeof(one));
    }

    if (lis->pem_cert) {
        mbedtls_ssl_init(&sock->ssl);
        mbedtls_ssl_config_init(&sock->conf);
        mbedtls_x509_crt_init(&sock->srvcert);
        mbedtls_pk_init(&sock->srvkey);
        mbedtls_x509_crt_init(&sock->cacert);
        mbedtls_x509_crt_init(&sock->clicert);
        mbedtls_pk_init(&sock->clikey);
        fg_tls_cfg_copy(&sock->cfg, &lis->cfg);
        sock->is_tls = 1;
        ret = mbedtls_x509_crt_parse(&sock->srvcert, (const unsigned char *) lis->pem_cert,
                                     strlen(lis->pem_cert) + 1);
        if (ret == 0) {
            ret = mbedtls_pk_parse_key(&sock->srvkey, (const unsigned char *) lis->pem_key,
                                       strlen(lis->pem_key) + 1, (const unsigned char *) sock->cfg.passphrase,
                                       sock->cfg.passphrase ? strlen(sock->cfg.passphrase) : 0, mbedtls_ctr_drbg_random,
                                       &fg_drbg);
        }
        if (ret == 0) {
            ret = mbedtls_ssl_config_defaults(&sock->conf, MBEDTLS_SSL_IS_SERVER, MBEDTLS_SSL_TRANSPORT_STREAM,
                                              MBEDTLS_SSL_PRESET_DEFAULT);
        }
        if (ret == 0) {
            mbedtls_ssl_conf_rng(&sock->conf, mbedtls_ctr_drbg_random, &fg_drbg);
            ret = mbedtls_ssl_conf_own_cert(&sock->conf, &sock->srvcert, &sock->srvkey);
        }
        if (ret == 0) {
            ret = fg_tls_apply(sock, 0, 0);
        }
        if (ret == 0) {
            ret = mbedtls_ssl_setup(&sock->ssl, &sock->conf);
        }
        if (ret != 0) {
            sock->in_use = 1;
            fg_socket_release(sock);
            return fg_throw_mbedtls(ctx, "TLS server setup", ret);
        }
        mbedtls_ssl_set_bio(&sock->ssl, &sock->net, mbedtls_net_send, mbedtls_net_recv, NULL);
        sock->hs_pending = 1;
    }
    sock->in_use = 1;
    return JS_NewInt32(ctx, id);
}

/* poll(readIds, timeoutMs, writeIds) -> [readable ids, writable ids]. A listener is readable when a connection
   waits to be accepted. Ids that no longer exist are reported as readable so the caller can find out. */
static uint32_t fg_array_length(JSContext *ctx, JSValueConst arr)
{
    uint32_t n = 0;
    JSValue lenv = JS_GetPropertyStr(ctx, arr, "length");
    JS_ToUint32(ctx, &n, lenv);
    JS_FreeValue(ctx, lenv);
    return n;
}

static JSValue fg_poll(JSContext *ctx, JSValueConst this_val, int argc, JSValueConst *argv)
{
    JSValue out, rd_out, wr_out;
    uint32_t nr, nw = 0, n, i, found_r = 0, found_w = 0;
    int32_t timeout = 0;
    int32_t *ids;
    int *ready;
    int *is_write;

    nr = fg_array_length(ctx, argv[0]);
    if (argc > 2 && !JS_IsUndefined(argv[2])) {
        nw = fg_array_length(ctx, argv[2]);
    }
    if (argc > 1) {
        JS_ToInt32(ctx, &timeout, argv[1]);
    }
    n = nr + nw;
    out = JS_NewArray(ctx);
    rd_out = JS_NewArray(ctx);
    wr_out = JS_NewArray(ctx);
    JS_SetPropertyUint32(ctx, out, 0, rd_out);
    JS_SetPropertyUint32(ctx, out, 1, wr_out);
    rd_out = JS_GetPropertyUint32(ctx, out, 0);
    wr_out = JS_GetPropertyUint32(ctx, out, 1);
    if (n == 0) {
        JS_FreeValue(ctx, rd_out);
        JS_FreeValue(ctx, wr_out);
        return out;
    }
    ids = (int32_t *) calloc(n, sizeof(int32_t));
    ready = (int *) calloc(n, sizeof(int));
    is_write = (int *) calloc(n, sizeof(int));
    if (!ids || !ready || !is_write) {
        free(ids);
        free(ready);
        free(is_write);
        JS_FreeValue(ctx, rd_out);
        JS_FreeValue(ctx, wr_out);
        JS_FreeValue(ctx, out);
        return JS_ThrowOutOfMemory(ctx);
    }
    for (i = 0; i < n; i++) {
        JSValue v = JS_GetPropertyUint32(ctx, i < nr ? argv[0] : argv[2], i < nr ? i : i - nr);
        JS_ToInt32(ctx, &ids[i], v);
        JS_FreeValue(ctx, v);
        is_write[i] = i >= nr;
    }

    for (i = 0; i < n; i++) {
        fg_socket *sock;
        if (ids[i] < 0 || ids[i] >= FG_MAX_SOCKETS || !fg_sockets[ids[i]].in_use) {
            ready[i] = 1; /* closed under us: let the caller find out */
            timeout = 0;
            continue;
        }
        sock = &fg_sockets[ids[i]];
        /* Data already decrypted and buffered inside TLS never wakes the descriptor again. */
        if (!is_write[i] && sock->is_tls && !sock->hs_pending && mbedtls_ssl_get_bytes_avail(&sock->ssl) > 0) {
            ready[i] = 1;
            timeout = 0;
        }
    }

#ifdef _WIN32
    {
        fd_set rset, wset;
        struct timeval tv;
        int any = 0;
        FD_ZERO(&rset);
        FD_ZERO(&wset);
        for (i = 0; i < n; i++) {
            if (!ready[i] && any < FD_SETSIZE - 1) {
                FD_SET((SOCKET) fg_sockets[ids[i]].net.fd, is_write[i] ? &wset : &rset);
                any++;
            }
        }
        tv.tv_sec = timeout / 1000;
        tv.tv_usec = (timeout % 1000) * 1000;
        if (any && select(0, &rset, &wset, NULL, &tv) > 0) {
            for (i = 0; i < n; i++) {
                if (!ready[i] && FD_ISSET((SOCKET) fg_sockets[ids[i]].net.fd, is_write[i] ? &wset : &rset)) {
                    ready[i] = 1;
                }
            }
        } else if (!any && timeout > 0) {
            Sleep((DWORD) timeout);
        }
    }
#else
    {
        struct pollfd *pfds = (struct pollfd *) calloc(n, sizeof(struct pollfd));
        if (pfds) {
            for (i = 0; i < n; i++) {
                pfds[i].fd = ready[i] ? -1 : fg_sockets[ids[i]].net.fd;
                pfds[i].events = is_write[i] ? POLLOUT : POLLIN;
            }
            if (poll(pfds, n, timeout) > 0) {
                for (i = 0; i < n; i++) {
                    if (pfds[i].fd >= 0 && pfds[i].revents) {
                        ready[i] = 1;
                    }
                }
            }
            free(pfds);
        }
    }
#endif

    for (i = 0; i < n; i++) {
        if (ready[i]) {
            if (is_write[i]) {
                JS_SetPropertyUint32(ctx, wr_out, found_w++, JS_NewInt32(ctx, ids[i]));
            } else {
                JS_SetPropertyUint32(ctx, rd_out, found_r++, JS_NewInt32(ctx, ids[i]));
            }
        }
    }
    free(ids);
    free(ready);
    free(is_write);
    JS_FreeValue(ctx, rd_out);
    JS_FreeValue(ctx, wr_out);
    return out;
}

/* address(id, peer) -> [ip, port, family] of the local end, or of the peer when `peer` is true. */
static JSValue fg_address(JSContext *ctx, JSValueConst this_val, int argc, JSValueConst *argv)
{
    int32_t id;
    fg_socket *sock;
    struct sockaddr_storage ss;
    socklen_t sl = sizeof(ss);
    char host[64];
    char serv[16];
    int peer = argc > 1 && JS_ToBool(ctx, argv[1]);
    JSValue arr;

    if (JS_ToInt32(ctx, &id, argv[0])) {
        return JS_EXCEPTION;
    }
    sock = fg_socket_get(ctx, id);
    if (!sock) {
        return JS_EXCEPTION;
    }
    memset(&ss, 0, sizeof(ss));
    if ((peer ? getpeername(sock->net.fd, (struct sockaddr *) &ss, &sl)
              : getsockname(sock->net.fd, (struct sockaddr *) &ss, &sl)) != 0) {
        return JS_NULL;
    }
    if (ss.ss_family == FG_AF_UNIX) {
        struct fg_sockaddr_un *un = (struct fg_sockaddr_un *) &ss;
        arr = JS_NewArray(ctx);
        JS_SetPropertyUint32(ctx, arr, 0, JS_NewString(ctx, un->sun_path));
        JS_SetPropertyUint32(ctx, arr, 1, JS_NewInt32(ctx, 0));
        JS_SetPropertyUint32(ctx, arr, 2, JS_NewString(ctx, "unix"));
        return arr;
    }
    if (getnameinfo((struct sockaddr *) &ss, sl, host, sizeof(host), serv, sizeof(serv),
                    NI_NUMERICHOST | NI_NUMERICSERV) != 0) {
        return JS_NULL;
    }
    arr = JS_NewArray(ctx);
    JS_SetPropertyUint32(ctx, arr, 0, JS_NewString(ctx, host));
    JS_SetPropertyUint32(ctx, arr, 1, JS_NewInt32(ctx, atoi(serv)));
    JS_SetPropertyUint32(ctx, arr, 2, JS_NewString(ctx, ss.ss_family == AF_INET6 ? "IPv6" : "IPv4"));
    return arr;
}

